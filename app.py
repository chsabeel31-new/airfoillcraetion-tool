                "the engine: the load is the average of the chord distribution "
                "and an ellipse of equal area. It ignores sweep, twist and "
                "compressibility, so use it as a first-cut tip-stall check "
                "only — where the local cl curve approaches Cl_max is where "
                "stall starts. A lifting-line or vortex-lattice solution is "
                "the next step up."
