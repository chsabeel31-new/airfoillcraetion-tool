def fill(fn):
    """
    Kwargs that make a widget fill its container, for whatever Streamlit
    version is installed.

    Streamlit 1.49 deprecated use_container_width in favour of width; pinning
    one spelling would either break on old versions or emit deprecation
    warnings on new ones, so the parameter is chosen by introspection.
    """
    try:
        params = inspect.signature(fn).parameters
    except (TypeError, ValueError):
        return {}
    if "width" in params:
        return {"width": "stretch"}
    if "use_container_width" in params:
        return {"use_container_width": True}
    return {}


