def clamp(value, lo=None, hi=None, fallback=0.0):
    """
    Keep a config value inside its widget bounds.

    A hand-edited or out-of-date config JSON would otherwise make Streamlit
    raise before the Reset button is reachable.
    """
    try:
        v = float(value)
    except (TypeError, ValueError):
        v = float(fallback)
    if not np.isfinite(v):
        v = float(fallback)
    if lo is not None:
        v = max(v, float(lo))
    if hi is not None:
        v = min(v, float(hi))
    return v


def pick(options, value, default_index=0):
    """Index of value in options, tolerating a value that is not there."""
    try:
        return options.index(value)
    except (ValueError, AttributeError):
        return default_index


def merge_cfg(template, loaded):
    """
    Recursively overlay a loaded config onto the default template.

    Keys absent from the upload keep their default, and unknown keys are
    dropped, so a partial or stale JSON cannot leave the app in a state where
    a later cfg[...] lookup raises.
    """
    out = copy.deepcopy(template)
    if not isinstance(loaded, dict):
        return out
    for key, val in loaded.items():
        if key not in out:
            continue
        if isinstance(out[key], dict) and isinstance(val, dict):
            out[key] = merge_cfg(out[key], val)
        elif not isinstance(out[key], dict) and not isinstance(val, dict):
            out[key] = val
    return out


def run_key_of(cfg):
    """Short stable hash of a config, used as a cache key."""
    blob = json.dumps(cfg, sort_keys=True, default=str).encode("utf-8")
    return hashlib.sha1(blob).hexdigest()[:12]


